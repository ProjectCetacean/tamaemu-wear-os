"""CLI regressions: each fixture changes a public documentation boundary."""
import pathlib
import hashlib
import subprocess
import sys
import tempfile
import unittest

SCRIPT = pathlib.Path(__file__).resolve().parents[1] / 'check-public-docs.py'
REQUIRED = ('README.md', 'CONTRIBUTING.md', 'THIRD_PARTY_NOTICES.md',
            'docs/WEAR_OS.md', 'docs/VERIFICATION.md', 'docs/RELEASE_NOTES.md')


class PublicDocsTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = pathlib.Path(self.temp.name)
        for name in REQUIRED:
            self.write(name, '# Guide\n\nUse local firmware.\n')

    def write(self, name, content):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')

    def run_gate(self):
        return subprocess.run([sys.executable, str(SCRIPT), '--export-root', str(self.root)],
                              capture_output=True, text=True)

    def assert_rejected(self, rule):
        result = self.run_gate()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn(rule, result.stdout + result.stderr)

    def test_valid_export_and_code_identifiers(self):
        self.write('README.md', '# Guide\n\n`dynamic framework` [guide](docs/WEAR_OS.md#guide).\n'
                   '\n```python\n# TODO: robust — framework\nx = "[bad](../../outside)"\n```\n'
                   '\n~~~text\nTODO — robust\n~~~\n')
        result = self.run_gate()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_future_markdown_is_discovered(self):
        self.write('docs/future-guide.md', '# Future\n\nA robust emulator.\n')
        self.assert_rejected('filler')

    def test_placeholder_and_tool_credit_are_rejected(self):
        for text, rule in [('TODO: explain installation.', 'placeholder'),
                           ('Co-authored-by: assistant', 'tool-credit'),
                           ('Generated by ChatGPT.', 'tool-credit'),
                           ('No data loss is possible.', 'unsupported-claim'),
                           ('The app is production-ready.', 'unsupported-claim'),
                           ('The app has zero latency.', 'unsupported-claim'),
                           ('A guide — use it.', 'em-dash')]:
            with self.subTest(text=text):
                self.write('README.md', '# Guide\n\n' + text + '\n')
                self.assert_rejected(rule)

    def test_missing_required_document(self):
        (self.root / 'docs/WEAR_OS.md').unlink()
        self.assert_rejected('required')

    def test_empty_export_fails_closed(self):
        for path in self.root.rglob('*.md'):
            path.unlink()
        self.assert_rejected('no-documents')

    def test_link_escape_schemes_and_symlinks(self):
        for target in ['../../outside.md', '%2e%2e/%2e%2e/outside',
                       'javascript:alert(1)', 'file:///etc/passwd', '//host/file']:
            with self.subTest(target=target):
                self.write('README.md', '# Guide\n\n[bad](' + target + ')\n')
                self.assert_rejected('link')
        self.write('README.md', '# Guide\n\n[bad](docs/linked.md)\n')
        (self.root / 'docs/linked.md').symlink_to('/etc/passwd')
        self.assert_rejected('symlink')

    def test_root_links_duplicate_unicode_anchors_and_reference_links(self):
        self.write('.github/guide.md', '# Café & input\n\n# Café & input\n')
        self.write('README.md', '# Guide\n\n[one](/.github/guide.md#café--input)\n'
                   '[two][second]\n\n[second]: .github/guide.md#café--input-1\n')
        self.assertEqual(self.run_gate().returncode, 0)
        self.write('README.md', '# Guide\n\n[bad](.github/guide.md#absent)\n')
        self.assert_rejected('anchor')

    def test_html_destinations_cannot_escape_link_checks(self):
        self.write('README.md', '# Guide\n\n<a href="../../outside.md">Guide</a>\n')
        self.assert_rejected('link')

    def test_upstream_prose_exemption_is_exact_content_only(self):
        source = SCRIPT.parents[1] / 'packaging/README.txt'
        self.write('packaging/README.txt', source.read_text(encoding='utf-8'))
        self.assertEqual(self.run_gate().returncode, 0)
        with (self.root / 'packaging/README.txt').open('a') as output:
            output.write('\nA robust port.\n')
        self.assert_rejected('filler')

    def test_synced_upstream_packaging_exemption_uses_verified_bytes(self):
        data = (SCRIPT.parents[1] / 'packaging/README.txt').read_bytes()
        self.assertEqual(hashlib.sha256(data).hexdigest(),
                         'd71c092a6455df26347b3f1d087b4aac6cf16c7c5a091d1bceca9c2efb4372ee')
        self.write('packaging/README.txt', data.decode('utf-8'))
        result = self.run_gate()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)

    def test_synced_upstream_packaging_exemption_is_path_specific(self):
        data = (SCRIPT.parents[1] / 'packaging/README.txt').read_text(encoding='utf-8')
        self.write('docs/desktop-packaging.md', data)
        self.assert_rejected('em-dash')

    def test_synced_upstream_packaging_mutation_loses_exemption(self):
        data = (SCRIPT.parents[1] / 'packaging/README.txt').read_text(encoding='utf-8')
        self.write('packaging/README.txt', '\n' + data)
        self.assert_rejected('em-dash')

    def test_missing_reference_link_fails(self):
        self.write('README.md', '# Guide\n\n[guide][missing]\n')
        self.assert_rejected('link')

    def test_invalid_utf8_and_unreadable_documents(self):
        (self.root / 'README.md').write_bytes(b'\xff')
        self.assert_rejected('read')
        self.write('README.md', '# Guide\n')
        (self.root / 'README.md').chmod(0)
        self.addCleanup(lambda: (self.root / 'README.md').chmod(0o644))
        self.assert_rejected('read')

    def test_private_process_documents(self):
        self.write('docs/RESUME-STATE.md', '# State\n\nPending release work.\n')
        self.assert_rejected('private-document')

    def test_legal_text_preserved_without_style_lint(self):
        self.write('licenses/Example.txt', 'Copyright 2021.\nA dynamic framework — provided AS IS.\n')
        self.write('README.md', '# Guide\n\n[License](licenses/Example.txt)\n')
        self.assertEqual(self.run_gate().returncode, 0)
        self.write('THIRD_PARTY_NOTICES.md', '# Notices\n\nA robust port.\n')
        self.assert_rejected('filler')

    def test_real_candidate(self):
        result = subprocess.run([sys.executable, str(SCRIPT), '--root', str(SCRIPT.parents[1])],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)


if __name__ == '__main__':
    unittest.main()
